#!/usr/bin/env bash
# Writes agent/tests/routine_fixtures.h: routine release key vectors for
# test_agent_trust.c, signed with throwaway P-256 keys made here by openssl
# (a stand-in release key, a key that is not the release key, two routine
# keys). Signatures stay valid, so the header is committed; rerun this only to
# change the vectors. The statement bytes must match the hub's
# (OMINULL-ROUTINE-KEYS-V1, OMINULL-RELEASE-V1).
set -euo pipefail
OUT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/routine_fixtures.h"
W="$(mktemp -d)"
trap 'rm -rf "$W"' EXIT

key() { openssl ecparam -name prime256v1 -genkey -noout -out "$W/$1.pem" 2>/dev/null; }
xy() { openssl ec -in "$W/$1.pem" -pubout -outform DER 2>/dev/null | tail -c 64 | od -An -v -tx1 | tr -d ' \n'; }
pubpem() { openssl ec -in "$W/$1.pem" -pubout 2>/dev/null; }
sign() { printf '%s' "$2" > "$W/msg"; openssl dgst -sha256 -sign "$W/$1.pem" "$W/msg" | base64 -w0; }
cstr() { printf '"'; printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' | awk 'BEGIN{ORS=""} NR>1{print "\\x0a\"\""} {print}'; [ "${1: -1}" = $'\n' ] && printf '\\x0a""'; printf '"'; }

for k in release other ra rb; do key "$k"; done
RXY=$(xy release); AXY=$(xy ra); BXY=$(xy rb)
AID=1111111111111111; BID=2222222222222222
LIST_AB="$AID:$AXY,$BID:$BXY"
LIST_A="$AID:$AXY"
stmt() { printf 'OMINULL-ROUTINE-KEYS-V1\nepoch=%s\nkeys=%s\n' "$1" "$2"; }
S5_AB="$(stmt 5 "$LIST_AB")"$'\n'
S5_A="$(stmt 5 "$LIST_A")"$'\n'
S4_A="$(stmt 4 "$LIST_A")"$'\n'
S6_NONE="$(stmt 6 "")"$'\n'
S7_AB="$(stmt 7 "$LIST_AB")"$'\n'
UPD="$(printf 'OMINULL-RELEASE-V1\npackage=ominull-agent_9.9.9_amd64.deb\nversion=9.9.9\nsha256=%s\n' "$(printf 'ab%.0s' $(seq 32))")"$'\n'
PKG=$'ominull test package\n'
# The trust bundle statement test_agent_trust.c offers (trust_fixtures.h).
TB="$(grep '^#define FX_TB_STATEMENT ' "$(dirname "$OUT")/trust_fixtures.h" | sed -e 's/^#define FX_TB_STATEMENT "//' -e 's/"""$//' -e 's/\\x0a""/\n/g' -e 's/\\x0a$//')"$'\n'

declare -a VALID=()
emit() {   # name signer message
    local s; s=$(sign "$2" "$3")
    printf '#define %s "%s"\n' "$1" "$s"
    case "$2" in release) x=$RXY;; ra) x=$AXY;; rb) x=$BXY;; *) return;; esac
    VALID+=("{\"$x\", $(cstr "$3"), \"$s\"}")
}
{
    echo "/* Generated by agent/tests/gen_routine_fixtures.sh. Do not edit. */"
    echo "#define FXR_RELEASE_XY \"$RXY\""
    printf '#define FXR_RELEASE_PEM %s\n' "$(cstr "$(pubpem release)"$'\n')"
    echo "#define FXR_A_ID \"$AID\""
    echo "#define FXR_A_XY \"$AXY\""
    printf '#define FXR_A_PEM %s\n' "$(cstr "$(pubpem ra)"$'\n')"
    echo "#define FXR_B_ID \"$BID\""
    echo "#define FXR_B_XY \"$BXY\""
    echo "#define FXR_LIST_AB \"$LIST_AB\""
    echo "#define FXR_LIST_A \"$LIST_A\""
    printf '#define FXR_STMT_5_AB %s\n' "$(cstr "$S5_AB")"
    emit FXR_SIG_5_AB release "$S5_AB"
    emit FXR_SIG_5_AB_WRONG other "$S5_AB"
    emit FXR_SIG_5_A release "$S5_A"
    emit FXR_SIG_4_A release "$S4_A"
    emit FXR_SIG_6_NONE release "$S6_NONE"
    emit FXR_SIG_7_AB_BY_A ra "$S7_AB"
    printf '#define FXR_UPDATE_STMT %s\n' "$(cstr "$UPD")"
    emit FXR_UPDATE_SIG_R release "$UPD"
    emit FXR_UPDATE_SIG_A ra "$UPD"
    emit FXR_UPDATE_SIG_W other "$UPD"
    printf '#define FXR_PKG %s\n' "$(cstr "$PKG")"
    emit FXR_PKG_SIG_R release "$PKG"
    emit FXR_PKG_SIG_A ra "$PKG"
    emit FXR_PKG_SIG_B rb "$PKG"
    emit FXR_TB_SIG_BY_A ra "$TB"
    printf '#define FXR_VALID {'
    for v in "${VALID[@]}"; do printf ' \\\n    %s,' "$v"; done
    printf ' \\\n}\n'
} > "$OUT"
echo "wrote $OUT"
